import io
from datetime import datetime, timezone
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

def generate_pdf_report(title: str, query: str, answer: str, citations: list) -> io.BytesIO:
    """Generates a professional PDF document for an AI analysis or answer."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    
    # Custom styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#1e1b4b'),
        spaceAfter=6
    )
    subtitle_style = ParagraphStyle(
        'DocSub',
        parent=styles['Normal'],
        fontSize=10,
        leading=13,
        textColor=colors.HexColor('#64748b'),
        spaceAfter=14
    )
    section_heading = ParagraphStyle(
        'SectionHead',
        parent=styles['Heading2'],
        fontSize=13,
        leading=16,
        textColor=colors.HexColor('#4338ca'),
        spaceBefore=12,
        spaceAfter=6
    )
    body_style = ParagraphStyle(
        'BodyDark',
        parent=styles['BodyText'],
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#1e293b'),
        spaceAfter=8
    )
    cite_style = ParagraphStyle(
        'CiteText',
        parent=styles['Normal'],
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#475569')
    )

    story = []

    # Title & Header
    story.append(Paragraph(title or "RAG Intelligence Report", title_style))
    now_str = datetime.now(timezone.utc).strftime("%B %d, %Y at %H:%M UTC")
    story.append(Paragraph(f"Generated by Multi-Document RAG Intelligence Platform • {now_str}", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#e2e8f0"), spaceAfter=14))

    # Query Section
    story.append(Paragraph("Inquiry / Prompt", section_heading))
    clean_query = query.replace("<", "&lt;").replace(">", "&gt;").replace("\n", "<br/>")
    story.append(Paragraph(f"<b>{clean_query}</b>", body_style))
    story.append(Spacer(1, 8))

    # Answer Section
    story.append(Paragraph("Synthesized Intelligence & Analysis", section_heading))
    clean_answer = answer.replace("<", "&lt;").replace(">", "&gt;").replace("\n", "<br/>")
    story.append(Paragraph(clean_answer, body_style))
    story.append(Spacer(1, 14))

    # Citations & Evidentiary Sources Table
    if citations:
        story.append(Paragraph("Evidentiary Sources & Document Citations", section_heading))
        table_data = [
            [
                Paragraph("<b>#</b>", cite_style),
                Paragraph("<b>Source Document</b>", cite_style),
                Paragraph("<b>Page</b>", cite_style),
                Paragraph("<b>Verified Excerpt</b>", cite_style)
            ]
        ]
        
        for idx, cit in enumerate(citations, 1):
            fname = cit.get("filename", "Unknown")
            pnum = str(cit.get("page_number", 1))
            excerpt = cit.get("excerpt", "")[:160].replace("<", "&lt;").replace(">", "&gt;")
            table_data.append([
                Paragraph(str(idx), cite_style),
                Paragraph(fname, cite_style),
                Paragraph(pnum, cite_style),
                Paragraph(f'"{excerpt}..."', cite_style)
            ])

        col_widths = [25, 120, 45, 340]
        cite_table = Table(table_data, colWidths=col_widths)
        cite_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#f1f5f9')),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(cite_table)

    doc.build(story)
    buffer.seek(0)
    return buffer
